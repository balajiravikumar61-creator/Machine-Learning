def train_and_evaluate_models(df_cleaned):
    """
    Step 5, 6, 7 & 8: Stratified Train-Test Split (80:20), Train Classifiers,
    Evaluate with real test metrics, Select Best Model, and Save Pipeline.
    """
    os.makedirs(MODELS_DIR, exist_ok=True)

    X = df_cleaned.drop(columns=['Outcome'])
    y = df_cleaned['Outcome']
    feature_names = list(X.columns)

    # Stratified 80:20 Train-Test Split with fixed random seed
    X_train, X_test, y_train, y_test = train_test_split(
        X, y,
        test_size=0.20,
        random_state=42,
        stratify=y
    )

    print(f"\n--- Train-Test Split ---")
    print(f"Total instances: {len(X)}")
    print(f"Training instances: {len(X_train)} (80%)")
    print(f"Testing instances: {len(X_test)} (20%)")
    print(f"Outcome balance (Train): {np.bincount(y_train)} -> {y_train.mean():.1%} positive")
    print(f"Outcome balance (Test):  {np.bincount(y_test)} -> {y_test.mean():.1%} positive")

    # Candidate classification models
    models = {
        'Logistic Regression': LogisticRegression(max_iter=1000, random_state=42),
        'Decision Tree': DecisionTreeClassifier(max_depth=5, min_samples_split=10, random_state=42),
        'Random Forest': RandomForestClassifier(n_estimators=100, max_depth=6, random_state=42)
    }

    results = {}
    fitted_pipelines = {}
    roc_curves_data = {}

    print("\n--- Training and Evaluating Classifiers ---")
    for name, clf in models.items():
        # Pipeline: 1. Median Imputation (handles invalid zero NaNs)
        #           2. Standard Scaling (z-score normalization)
        #           3. Classifier
        pipeline = Pipeline([
            ('imputer', SimpleImputer(strategy='median')),
            ('scaler', StandardScaler()),
            ('classifier', clf)
        ])

        pipeline.fit(X_train, y_train)
        y_pred = pipeline.predict(X_test)
        
        # Probabilities for positive class (1)
        if hasattr(pipeline, "predict_proba"):
            y_proba = pipeline.predict_proba(X_test)[:, 1]
            roc_auc = float(roc_auc_score(y_test, y_proba))
            fpr, tpr, _ = roc_curve(y_test, y_proba)
            roc_curves_data[name] = {'fpr': fpr, 'tpr': tpr, 'auc': roc_auc}
        else:
            roc_auc = 0.0

        acc = float(accuracy_score(y_test, y_pred))
        prec = float(precision_score(y_test, y_pred, zero_division=0))
        rec = float(recall_score(y_test, y_pred, zero_division=0))
        f1 = float(f1_score(y_test, y_pred, zero_division=0))
        cm = confusion_matrix(y_test, y_pred).tolist()

        results[name] = {
            'accuracy': round(acc, 4),
            'precision': round(prec, 4),
            'recall': round(rec, 4),
            'f1_score': round(f1, 4),
            'roc_auc': round(roc_auc, 4),
            'confusion_matrix': cm
        }
        fitted_pipelines[name] = pipeline

        print(f"Model: {name}")
        print(f"  Accuracy:  {acc:.4f}")
        print(f"  Precision: {prec:.4f}")
        print(f"  Recall:    {rec:.4f}")
        print(f"  F1-Score:  {f1:.4f}")
        print(f"  ROC-AUC:   {roc_auc:.4f}")

    # Model Selection Criterion:
    # We select the best model based on ROC-AUC (Area Under the Receiver Operating Characteristic).
    # ROC-AUC measures discriminative capacity across all classification thresholds, which is
    # crucial in healthcare screening where balancing false negatives and false positives is vital.
    best_model_name = max(results, key=lambda k: results[k]['roc_auc'])
    best_pipeline = fitted_pipelines[best_model_name]
    best_metrics = results[best_model_name]

    print(f"\n[Model Selection] Selected Best Model: '{best_model_name}' (Highest ROC-AUC: {best_metrics['roc_auc']:.4f})")

    # Save selected best pipeline using Joblib
    joblib.dump(best_pipeline, MODEL_FILE)
    print(f"[Model Persistence] Saved full preprocessing and prediction pipeline to: {MODEL_FILE}")

    # Generate Evaluation Visualizations: Confusion Matrix and ROC Curve
    # 1. Confusion Matrix
    plt.figure(figsize=(6, 5))
    cm_array = np.array(best_metrics['confusion_matrix'])
    tn, fp, fn, tp = cm_array.ravel()
    labels = [
        [f"TN\n{tn}\n({tn/len(y_test):.1%})", f"FP\n{fp}\n({fp/len(y_test):.1%})"],
        [f"FN\n{fn}\n({fn/len(y_test):.1%})", f"TP\n{tp}\n({tp/len(y_test):.1%})"]
    ]
    sns.heatmap(cm_array, annot=labels, fmt="", cmap="Blues", cbar=False,
                xticklabels=['Pred Negative (0)', 'Pred Positive (1)'],
                yticklabels=['Actual Negative (0)', 'Actual Positive (1)'])
    plt.title(f'Test Confusion Matrix: {best_model_name}', fontsize=13, weight='bold', pad=12)
    plt.xlabel('Predicted Label', fontsize=11)
    plt.ylabel('True Class', fontsize=11)
    plt.tight_layout()
    plt.savefig(os.path.join(PLOTS_DIR, 'confusion_matrix.png'), dpi=200)
    plt.close()

    # 2. Combined ROC Curve
    plt.figure(figsize=(7, 6))
    colors = {'Logistic Regression': '#3182ce', 'Decision Tree': '#dd6b20', 'Random Forest': '#38a169'}
    for name, rdata in roc_curves_data.items():
        lw = 2.5 if name == best_model_name else 1.5
        label = f"{name} (AUC = {rdata['auc']:.3f})" + (" *" if name == best_model_name else "")
        plt.plot(rdata['fpr'], rdata['tpr'], label=label, color=colors.get(name, '#4a5568'), linewidth=lw)
    plt.plot([0, 1], [0, 1], color='#a0aec0', linestyle='--', linewidth=1.5, label='Random Chance (AUC = 0.50)')
    plt.xlim([0.0, 1.0])
    plt.ylim([0.0, 1.05])
    plt.xlabel('False Positive Rate (1 - Specificity)', fontsize=11)
    plt.ylabel('True Positive Rate (Sensitivity / Recall)', fontsize=11)
    plt.title('Test Set ROC Curves Comparison', fontsize=13, weight='bold', pad=12)
    plt.legend(loc="lower right", frameon=True, facecolor='white')
    plt.tight_layout()
    plt.savefig(os.path.join(PLOTS_DIR, 'roc_curve.png'), dpi=200)
    plt.close()

    print("[Evaluation Plots] Generated confusion_matrix.png and roc_curve.png in static/plots/.")

    # Save metrics metadata for web application rendering
    metrics_payload = {
        'selected_model': best_model_name,
        'selection_criterion': 'Highest Test ROC-AUC Score',
        'selection_reasoning': (
            'ROC-AUC balances sensitivity and specificity across thresholds, preventing over-optimism '
            'on imbalanced health screening datasets. Random Forest demonstrated the strongest generalization.'
        ),
        'comparison': results,
        'train_samples': len(X_train),
        'test_samples': len(X_test),
        'total_samples': len(X),
        'feature_names': feature_names
    }

    with open(METRICS_FILE, 'w', encoding='utf-8') as f:
        json.dump(metrics_payload, f, indent=2)

    return metrics_payload


