def ensure_dataset():
    """Ensure data/diabetes.csv exists with valid authentic records."""
    os.makedirs(DATA_DIR, exist_ok=True)
    
    if os.path.exists(DATA_FILE) and os.path.getsize(DATA_FILE) > 5000:
        # Check line count
        with open(DATA_FILE, 'r', encoding='utf-8') as f:
            lines = f.readlines()
        if len(lines) >= 768:
            print(f"[Data] Found existing dataset at {DATA_FILE} ({len(lines)-1} records).")
            return

    print(f"[Data] Initializing authentic Pima Indians Diabetes dataset at {DATA_FILE}...")
    try:
        # First attempt: Decode embedded base64 (offline-first, 100% reliable)
        decoded_bytes = base64.b64decode(EMBEDDED_PIMA_DATASET_B64)
        with open(DATA_FILE, 'wb') as f:
            f.write(decoded_bytes)
        print(f"[Data] Successfully written {DATA_FILE} from embedded authentic data.")
    except Exception as e:
        print(f"[Data] Local decoding failed ({e}), attempting online fetch from {DATASET_URL}...")
        try:
            urllib.request.urlretrieve(DATASET_URL, DATA_FILE)
            print(f"[Data] Successfully fetched dataset from {DATASET_URL}.")
        except Exception as net_err:
            raise RuntimeError(
                f"Could not initialize {DATA_FILE}. Please download the Pima Indians Diabetes dataset "
                f"from {DATASET_URL} and place it at {DATA_FILE}. Error: {net_err}"
            )


def load_and_preprocess_data():
    """
    Step 2 & 3: Load dataset, inspect characteristics, identify and handle invalid zero measurements.
    Returns: df_raw, df_cleaned, zero_summary
    """
    ensure_dataset()
    df_raw = pd.read_csv(DATA_FILE)
    print(f"\n--- Dataset Overview ---")
    print(f"Shape: {df_raw.shape[0]} rows, {df_raw.shape[1]} columns")
    print(f"Columns: {list(df_raw.columns)}")
    print(f"Missing values (standard nulls): {df_raw.isnull().sum().to_dict()}")
    print(f"Duplicate records: {df_raw.duplicated().sum()}")

    # In the Pima dataset, 0 in measurement columns represents invalid/missing data.
    # Pregnancies = 0 is medically valid. Outcome = 0 is the negative class.
    zero_invalid_cols = ['Glucose', 'BloodPressure', 'SkinThickness', 'Insulin', 'BMI']
    zero_summary = {}
    
    df_cleaned = df_raw.copy()
    for col in zero_invalid_cols:
        count_zeros = (df_cleaned[col] == 0).sum()
        pct_zeros = (count_zeros / len(df_cleaned)) * 100
        zero_summary[col] = {
            'count': int(count_zeros),
            'percentage': round(float(pct_zeros), 2),
            'median_excluding_zeros': round(float(df_cleaned[df_cleaned[col] != 0][col].median()), 2)
        }
        # Replace invalid zeros with NaN for proper imputation
        df_cleaned[col] = df_cleaned[col].replace(0, np.nan)

    print("\n--- Invalid Zero Measurement Analysis ---")
    for col, info in zero_summary.items():
        print(f"  {col}: {info['count']} invalid zeros ({info['percentage']}%) -> Cleaned median: {info['median_excluding_zeros']}")

    return df_raw, df_cleaned, zero_summary


